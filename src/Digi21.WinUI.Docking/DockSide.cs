namespace Digi21.WinUI.Docking;

/// <summary>
/// The side of a dock target (the whole <see cref="DockSite"/> or another window) to dock to.
/// </summary>
public enum DockSide
{
    /// <summary>Dock to the left side.</summary>
    Left,

    /// <summary>Dock to the top side.</summary>
    Top,

    /// <summary>Dock to the right side.</summary>
    Right,

    /// <summary>Dock to the bottom side.</summary>
    Bottom,
}
